"""Pure helpers for the multimodal agent.

Nothing in this module imports Strands or AgentCore, so it can be unit tested
without those packages. It holds payload validation, media limits, ID rules,
log redaction, memory namespace templates and a small duplicate-request cache.
"""

import base64
import binascii
import hashlib
import json
import logging
import re
import threading
import time
from collections import OrderedDict
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple

# --- Memory namespace templates -------------------------------------------------
# Must match agentcore/config.py (tests/test_namespaces.py enforces it). Strategy
# IDs are generated by CloudFormation, so the strategies declare these fixed
# namespaces and the agent retrieves from the same paths.
FACTS_NAMESPACE = "/facts/{actorId}/"
PREFERENCES_NAMESPACE = "/preferences/{actorId}/"
SUMMARIES_NAMESPACE = "/summaries/{actorId}/{sessionId}/"
EPISODES_NAMESPACE = "/episodes/{actorId}/"

# --- Limits ---------------------------------------------------------------------
MAX_PROMPT_CHARS = 10_000
MAX_MEDIA_BYTES = 1_500_000  # decoded bytes (the base64 text is ~33% larger)
MAX_TRANSCRIPT_CHARS = 20_000
MAX_ID_LENGTH = 128
MAX_S3_URI_LENGTH = 1024
MIN_ID_LENGTH = 33  # AgentCore session IDs and the Lambda padding rule use 33

VALID_IMAGE_FORMATS = {"jpeg", "png", "gif", "webp"}
VALID_DOCUMENT_FORMATS = {"pdf", "csv", "doc", "docx", "xls", "xlsx", "html", "txt", "md"}
VALID_MEDIA_TYPES = {"image", "document", "video", "audio_transcript"}

_ID_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_\-]*$")
_S3_URI_PATTERN = re.compile(r"^s3://[a-z0-9][a-z0-9.\-]{1,61}[a-z0-9]/[^\s]+$")
_CHANNEL_PATTERN = re.compile(r"\[Channel:\s*([A-Za-z]+)\]")

DEFAULT_ACTOR_ID = "default-actor" + "0" * 20  # 33 characters
DEFAULT_SESSION_ID = "default-session" + "0" * 18  # 33 characters


def pad_id(value: str, min_length: int = MIN_ID_LENGTH) -> str:
    """Right-pad an ID with zeros to at least ``min_length`` characters.

    Same rule the Lambda applies before calling the runtime
    (``ljust(33, "0")``, so ``wa-user-573001234567`` gets 13 trailing zeros).
    """
    return value + "0" * max(0, min_length - len(value))


def sanitize_id(value: Any, default: str) -> str:
    """Return a safe actor/session ID, falling back to ``default`` when invalid."""
    if isinstance(value, str) and len(value) <= MAX_ID_LENGTH and _ID_PATTERN.match(value):
        return pad_id(value)
    return default


def hash_id(value: str) -> str:
    """Short, stable hash for logs and trace attributes (IDs contain phone numbers)."""
    return hashlib.sha256(value.encode("utf-8")).hexdigest()[:12]


def detect_channel(prompt: str) -> str:
    """Read the ``[Channel: whatsapp|instagram]`` tag added by the Lambda."""
    match = _CHANNEL_PATTERN.search(prompt or "")
    return match.group(1).lower() if match else "unknown"


def decoded_size(b64: str) -> int:
    """Size in bytes of a base64 string once decoded."""
    stripped = b64.rstrip("=")
    return (len(stripped) * 3) // 4


def sanitize_document_name(name: str) -> str:
    """Sanitize a document name for the Claude Converse API.

    Only alphanumeric characters, whitespace, hyphens, parentheses and square
    brackets are allowed, with no consecutive whitespace and no extension.
    """
    name = str(name or "")
    name_no_ext = name.rsplit(".", 1)[0] if "." in name else name
    sanitized = re.sub(r"[^a-zA-Z0-9\s\-\(\)\[\]]", " ", name_no_ext).strip()
    sanitized = re.sub(r"\s+", " ", sanitized)
    return sanitized or "document"


def validate_media(media: Any) -> Optional[str]:
    """Validate a media object. Returns a user-facing error message, or None if valid."""
    if not isinstance(media, dict):
        return "The attached media is not valid."

    media_type = media.get("type", "")
    media_format = media.get("format", "")
    media_data = media.get("data", "")

    if media_type not in VALID_MEDIA_TYPES:
        return "Unsupported media type."

    if media_type in ("image", "document"):
        valid = VALID_IMAGE_FORMATS if media_type == "image" else VALID_DOCUMENT_FORMATS
        label = "image" if media_type == "image" else "document"
        if media_format not in valid:
            return f"Unsupported {label} format: {media_format}. Supported: {', '.join(sorted(valid))}"
        if not isinstance(media_data, str) or not media_data:
            return f"The {label} is empty."
        if decoded_size(media_data) > MAX_MEDIA_BYTES:
            return f"The {label} is too large to process. Please send a smaller one (under 1.5 MB)."
        try:
            base64.b64decode(media_data, validate=True)
        except (binascii.Error, ValueError):
            return f"The {label} could not be read."

    if media_type == "video":
        uri = media.get("s3_uri")
        if not uri:
            return "Video S3 URI is missing."
        if not isinstance(uri, str) or len(uri) > MAX_S3_URI_LENGTH or not _S3_URI_PATTERN.match(uri):
            return "The video location is not valid."

    if media_type == "audio_transcript":
        if not isinstance(media_data, str) or len(media_data) > MAX_TRANSCRIPT_CHARS:
            return "The audio transcription is too long to process."

    return None


@dataclass
class AgentRequest:
    """A validated invocation request."""

    prompt: str
    actor_id: str
    session_id: str
    media: Optional[Dict[str, Any]] = None
    idempotency_key: Optional[str] = None
    channel: str = "unknown"
    user_id: Optional[str] = None  # verified canonical user id sent by the Lambda (not model output)


class PayloadError(ValueError):
    """Raised for payloads that must be rejected. ``str(error)`` is safe to show the user."""


_USER_ID_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_\-]{0,127}$")


def _clean_user_id(value: Any) -> Optional[str]:
    """Canonical user id as sent by the Lambda, or None when absent or malformed."""
    if isinstance(value, str) and _USER_ID_PATTERN.match(value):
        return value
    return None


def parse_request(payload: Any, session_id: Optional[str], header_actor_id: Optional[str]) -> AgentRequest:
    """Validate the raw payload and build an :class:`AgentRequest`.

    Actor ID precedence: payload ``actor_id``, then the custom request header,
    then a default. Invalid IDs fall back to the defaults instead of reaching memory.
    """
    if not isinstance(payload, dict):
        raise PayloadError("Invalid request.")

    prompt = payload.get("prompt", "")
    if prompt is None:
        prompt = ""
    if not isinstance(prompt, str):
        raise PayloadError("Invalid request.")
    if len(prompt) > MAX_PROMPT_CHARS:
        raise PayloadError("The message is too long to process.")

    media = payload.get("media")
    if media:
        error = validate_media(media)
        if error:
            raise PayloadError(error)
    else:
        media = None
        if not prompt.strip():
            raise PayloadError("Empty message.")

    key = payload.get("idempotency_key")
    if key is not None and not (isinstance(key, str) and 0 < len(key) <= MAX_ID_LENGTH):
        key = None

    actor_id = sanitize_id(payload.get("actor_id"), "")
    if not actor_id:
        actor_id = sanitize_id(header_actor_id, DEFAULT_ACTOR_ID)

    return AgentRequest(
        prompt=prompt,
        actor_id=actor_id,
        session_id=sanitize_id(session_id, DEFAULT_SESSION_ID),
        media=media,
        idempotency_key=key,
        channel=detect_channel(prompt),
        user_id=_clean_user_id(payload.get("user_id")),
    )


def memory_retrieval_namespaces(actor_id: str, session_id: str) -> Dict[str, Dict[str, Any]]:
    """Retrieval settings keyed by concrete namespace for one actor and session."""
    values = {"actorId": actor_id, "sessionId": session_id}
    settings = {
        FACTS_NAMESPACE: {"top_k": 20, "relevance_score": 0.3},
        PREFERENCES_NAMESPACE: {"top_k": 10, "relevance_score": 0.3},
        SUMMARIES_NAMESPACE: {"top_k": 3, "relevance_score": 0.3},
        EPISODES_NAMESPACE: {"top_k": 3, "relevance_score": 0.4},
    }
    resolved = {}
    for template, cfg in settings.items():
        resolved[template.format(**values)] = dict(cfg)
    return resolved


# --- Redaction -------------------------------------------------------------------
_REDACTIONS = [
    (re.compile(r"s3://[^\s\"']+"), "[redacted-location]"),
    (re.compile(r"arn:aws[a-z\-]*:[^\s\"']+"), "[redacted-arn]"),
    (re.compile(r"https?://[^\s\"']*(amazonaws\.com|twelvelabs\.io)[^\s\"']*"), "[redacted-url]"),
    (re.compile(r"\b\d{12}\b"), "[redacted-id]"),
    (re.compile(r"(?i)(x-api-key|api[_-]?key|secret|token)\s*[:=]\s*\S+"), r"\1=[redacted]"),
]
GENERIC_TOOL_ERROR = "The tool had a technical issue. Tell the user you had a technical issue processing that."


def redact_sensitive(text: str) -> str:
    """Strip locations, ARNs, account IDs and key-like values from text."""
    for pattern, replacement in _REDACTIONS:
        text = pattern.sub(replacement, text)
    return text


# --- Response text ---------------------------------------------------------------
def extract_text(message: Any) -> str:
    """Join the text blocks of a Strands message (``{"role": ..., "content": [...]}``)."""
    if not isinstance(message, dict):
        return str(message) if message else ""
    parts: List[str] = []
    for block in message.get("content", []) or []:
        if isinstance(block, dict) and isinstance(block.get("text"), str):
            parts.append(block["text"])
    return "\n".join(p for p in parts if p).strip()


# --- Duplicate request cache -----------------------------------------------------
class RecentResultCache:
    """Small bounded TTL cache so a retried delivery gets the same reply.

    Keyed by ``(actor_id, session_id, idempotency_key)``. It only covers retries
    that reach the same microVM; durable de-duplication happens at ingestion.
    """

    def __init__(self, max_items: int = 256, ttl_seconds: float = 300.0, clock=time.monotonic) -> None:
        self._items: "OrderedDict[Tuple[str, ...], Tuple[float, str]]" = OrderedDict()
        self._max = max_items
        self._ttl = ttl_seconds
        self._clock = clock
        self._lock = threading.Lock()

    def get(self, key: Tuple[str, ...]) -> Optional[str]:
        with self._lock:
            entry = self._items.get(key)
            if entry is None:
                return None
            stored_at, value = entry
            if self._clock() - stored_at > self._ttl:
                del self._items[key]
                return None
            self._items.move_to_end(key)
            return value

    def put(self, key: Tuple[str, ...], value: str) -> None:
        with self._lock:
            self._items[key] = (self._clock(), value)
            self._items.move_to_end(key)
            while len(self._items) > self._max:
                self._items.popitem(last=False)

    def __len__(self) -> int:
        return len(self._items)


# --- Structured logging ----------------------------------------------------------
class JsonFormatter(logging.Formatter):
    """One JSON object per line so CloudWatch Logs Insights can filter on fields."""

    def format(self, record: logging.LogRecord) -> str:
        entry: Dict[str, Any] = {
            "level": record.levelname,
            "logger": record.name,
            "message": record.getMessage(),
        }
        fields = getattr(record, "fields", None)
        if isinstance(fields, dict):
            entry.update(fields)
        if record.exc_info:
            entry["exception"] = redact_sensitive(self.formatException(record.exc_info))
        return json.dumps(entry, default=str)


def configure_logging(level: str = "INFO") -> None:
    """Install the JSON formatter on the root logger (idempotent)."""
    root = logging.getLogger()
    handler = logging.StreamHandler()
    handler.setFormatter(JsonFormatter())
    root.handlers = [handler]
    root.setLevel(level.upper() if isinstance(level, str) else "INFO")
